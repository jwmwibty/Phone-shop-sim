const {chromium}=require('/home/user/node_modules/playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl']});
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',e=>{errors.push('PAGE '+e.message);console.error('PAGEERROR',e.stack)});
 page.on('console',m=>{if(['error','warning'].includes(m.type())) console.log('CONSOLE',m.type(),m.text())});
 page.on('requestfailed',req=>console.log('FAILED',req.url(),req.failure()?.errorText));
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'load',timeout:60000});
 await page.waitForTimeout(3500);
 console.log('TITLE',await page.title());
 console.log('HUD',await page.locator('#objective-text').textContent(),await page.locator('#money-display').textContent(),await page.locator('#stat-shelves').textContent());
 console.log('WEBGL',await page.evaluate(()=>({rendering:typeof renderer!=='undefined', camera:typeof camera!=='undefined'?camera.type:'none',gl:!!document.querySelector('canvas').getContext('webgl')})));
 await page.screenshot({path:'/home/user/phone-shop-src/screen-initial.png'});
 await page.locator('#btn-menu-store').click();
 await page.waitForTimeout(500);
 console.log('SUPPLIER',await page.locator('#drawer-store').isVisible(), 'cards',await page.locator('#panel-brands .catalog-card').count());
 await page.screenshot({path:'/home/user/phone-shop-src/screen-supplier.png'});
 await page.locator('#tab-btn-furniture').click();
 console.log('FURNITURE',await page.locator('#panel-store-upgrades .catalog-card').count());
 await page.locator('#btn-close-store').click();
 await page.locator('#btn-menu-staff').click();
 console.log('UPGRADES',await page.locator('#drawer-staff').isVisible(),await page.locator('#panel-player-upgrades .catalog-card').count());
 await page.locator('#tab-btn-workers').click();
 console.log('STAFF',await page.locator('#panel-staff-upgrades .catalog-card').count());
 await page.screenshot({path:'/home/user/phone-shop-src/screen-staff.png'});
 await page.locator('#btn-close-staff').click();
 console.log('ERRORS',errors.length);
 await browser.close();
})();
